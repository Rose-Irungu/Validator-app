import { useEffect } from "react";
import { Link, useLocation } from "react-router-dom";
import ResultsNavbar from "../components/ResultsNavbar";
import ScoreBanner from "../components/ScoreBanner";
import SwotSection from "../components/SwotSection";
import Competitors from "../components/Competitors";
import MarketGaps from "../components/MarketGaps";
import GrowthStrategies from "../components/GrowthStrategies";
import Footer from "../layout/Footer";
import { getStoredAnalysis } from "../hooks/useValidateIdea";
import { shortTitle, formatScore } from "../utils/report";

export default function ResultsPage() {
  const { state } = useLocation();
  const stored = state?.result ? state : getStoredAnalysis();
  const input = stored?.input;
  const raw = stored?.result;
  const report = raw?.data && !raw?.swot ? raw.data : raw;

  useEffect(() => {
    window.scrollTo(0, 0);
  }, []);

  if (!report) {
    return (
      <div className="flex min-h-screen flex-col">
        <ResultsNavbar onDownload={() => {}} mailHref="mailto:" />
        <main className="flex flex-1 flex-col items-center justify-center gap-4 bg-white px-4 text-center">
          <h1 className="text-xl font-semibold text-black">No report to show yet</h1>
          <p className="text-sm text-gray-700">Run an analysis first and your report will appear here.</p>
          <Link
            to="/idea"
            className="rounded-sm bg-[#004B38] px-6 py-3 text-sm font-medium text-white transition hover:bg-[#003B2D]"
          >
            Validate an Idea
          </Link>
        </main>
        <Footer bg="bg-white" />
      </div>
    );
  }

  const title = shortTitle(input?.concept) || "Your idea";
  const mailHref = `mailto:?subject=${encodeURIComponent(`Validator report: ${title}`)}&body=${encodeURIComponent(
    `${title}\nViability score: ${formatScore(report.score)}/10\n\n${report.viabilityOverview || ""}`
  )}`;

  return (
    <div className="flex min-h-screen flex-col">
      <ResultsNavbar onDownload={() => window.print()} mailHref={mailHref} />

      <main className="flex-1 bg-white px-4 py-8 md:px-6 md:py-12">
        <div className="mx-auto flex max-w-4xl flex-col gap-10">
          <div>
            <p className="text-xs font-semibold uppercase tracking-wider text-[#004B38]">Validator Report</p>
            <h1 className="mt-3 text-2xl font-bold text-black md:text-3xl">{title}</h1>
            {report.targetCustomer && (
              <p className="mt-2 text-sm leading-relaxed text-gray-900 md:text-base">{report.targetCustomer}</p>
            )}
          </div>

          <ScoreBanner
            score={report.score}
            overview={report.viabilityOverview}
            confidence={report.confidence}
          />

          <SwotSection swot={report.swot} />
          <Competitors competitors={report.competitors} />

          <div className="flex flex-col gap-8">
            <MarketGaps gaps={report.gaps} />
            <GrowthStrategies strategies={report.strategies} />
          </div>

          <div className="rounded-md border border-[#F6E27A] bg-[#FFF6D6] px-4 py-4 text-sm leading-relaxed text-black">
            This report was generated by Validator based on the idea you submitted. Treat it as a starting point for
            your own research, not as financial or legal advice.
          </div>
        </div>
      </main>

      <Footer bg="bg-white" />
    </div>
  );
}